"""Extract the two public Chrome 157 H2 capabilities missing from pinned uTLS.

Input: one complete TLS record captured on loopback. Never serialize other fields.
"""
import argparse
import hashlib
from io import BytesIO
from pathlib import Path


def take(stream, n):
    value = stream.read(n)
    if len(value) != n:
        raise ValueError("truncated ClientHello")
    return value


def vector(stream, width):
    return take(stream, int.from_bytes(take(stream, width), "big"))


def generate(record):
    wire = BytesIO(record)
    if take(wire, 3) != bytes.fromhex("160301"):
        raise ValueError("expected initial TLS handshake record")
    hs = BytesIO(vector(wire, 2))
    if take(hs, 1) != b"\x01":
        raise ValueError("expected ClientHello")
    hello = BytesIO(vector(hs, 3))
    take(hello, 34)
    vector(hello, 1)
    vector(hello, 2)
    vector(hello, 1)
    extensions = BytesIO(vector(hello, 2))
    if hello.read() or hs.read() or wire.read():
        raise ValueError("unexpected trailing bytes")
    public = {}
    while kind := extensions.read(2):
        value = vector(extensions, 2)
        if kind in (b"\xca\x34", b"\x00\x0d"):
            if kind in public:
                raise ValueError("duplicate extension")
            public[kind] = value
    anchors = public[b"\xca\x34"]
    if hashlib.sha256(anchors).hexdigest() != "734236b257e52e7d202b222a0694fedf187c12b11a4fcc733dd00f3331b7f16c":
        raise ValueError("review changed trust anchor identifiers before publishing")
    sigs = public[b"\x00\x0d"]
    if len(sigs) == 26 and sigs[:2] == b"\x00\x18" and sigs[2] == sigs[3] and sigs[2] & 15 == 10:
        sigs = sigs[:2] + bytes.fromhex("0a0a") + sigs[4:]
    if sigs != bytes.fromhex("0018 0a0a 0904 0905 0906 0403 0804 0401 0503 0805 0501 0806 0601"):
        raise ValueError("unexpected Chrome 157 signature schemes")
    ids = ", ".join("0x" + sigs[i:i+2].hex() for i in range(2, len(sigs), 2))
    rows = ["\t" + " ".join(f"0x{b:02x}," for b in anchors[i:i+12]) for i in range(0, len(anchors), 12)]
    return ('// Code generated by tools/generate_v2_chrome_profile.py. DO NOT EDIT.\n'
            'package transport\n\nimport utls "github.com/refraction-networking/utls"\n\n'
            'var chrome157Signatures = [...]utls.SignatureScheme{' + ids + '}\n\n'
            'var chrome157Anchors = [...]byte{\n' + "\n".join(rows) + '\n}\n')


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--record", type=Path, help="single TLS record from a loopback sample")
    source.add_argument("--chrome", type=Path, help="sample local Chrome with the design branch tools on PYTHONPATH")
    args = parser.parse_args()
    output = Path(__file__).resolve().parents[1] / "v2/transport/chrome157.go"
    if args.chrome:
        from benchmark_clienthello import chrome
        hello = chrome(args.chrome, False, lambda msg, _: msg)
        record = b"\x16\x03\x01" + len(hello).to_bytes(2, "big") + hello
    else:
        record = args.record.read_bytes()
    output.write_text(generate(record), encoding="utf-8", newline="\n")
